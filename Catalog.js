function pick(exceptId) {
  var list = all()
  var except = Number(exceptId)
  var n = list.length
  if (n === 0) return null
  var i = Math.floor(Math.random() * n)
  var tries = 0
  while (n > 1 && Number(list[i].id) === except && tries < 16) {
    i = Math.floor(Math.random() * n)
    tries++
  }
  var chosen = list[i]
  return {
    id: Number(chosen.id),
    slug: String(chosen.slug),
    title: String(chosen.title),
    body: String(chosen.body)
  }
}

